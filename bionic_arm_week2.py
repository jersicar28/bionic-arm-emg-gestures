def preprocess_record(record_path):
    """
    Load a GRABMyo record and apply bandpass + notch filter
    to every channel.

    Returns
    -------
    filtered : (n_samples, n_channels) ndarray
    fs       : int, sampling frequency
    """
    record = wfdb.rdrecord(record_path)
    emg    = record.p_signal        # (n_samples, n_channels)
    fs     = record.fs

    nyq    = 0.5 * fs
    b_bp, a_bp = signal.butter(4, [20 / nyq, 450 / nyq], btype='band')
    b_n,  a_n  = signal.iirnotch(60 / (fs / 2), Q=30)

    filtered = np.zeros_like(emg)
    for ch in range(emg.shape[1]):
        tmp = signal.filtfilt(b_bp, a_bp, emg[:, ch])
        filtered[:, ch] = signal.filtfilt(b_n, a_n, tmp)

    return filtered, fs


# ============================================================
# STEP 2 — Time-Domain Feature Extraction (per window per channel)
#
#   MAV  Mean Absolute Value  — amplitude / muscle activation proxy
#   RMS  Root Mean Square     — signal power proxy
#   ZC   Zero Crossings       — frequency content proxy
#   WL   Waveform Length      — signal complexity proxy
#   SSC  Slope Sign Changes   — additional frequency proxy
#   VAR  Variance             — spread of signal energy
# ============================================================

def compute_features(window):
    """
    Compute 6 time-domain features for a single 1-D window.

    Parameters
    ----------
    window : 1-D ndarray of filtered EMG samples

    Returns
    -------
    dict {feature_name: scalar}
    """
    # Noise threshold — 1 % of peak-to-peak range
    ptp       = np.ptp(window)
    threshold = 0.01 * ptp if ptp > 0 else 1e-9

    mav = np.mean(np.abs(window))
    rms = np.sqrt(np.mean(window ** 2))

    # ZC — sign changes where magnitude of jump exceeds threshold
    zc = int(np.sum(
        (np.diff(np.sign(window)) != 0) &
        (np.abs(np.diff(window)) >= threshold)
    ))

    # WL — arc length of the waveform
    wl = float(np.sum(np.abs(np.diff(window))))

    # SSC — slope sign changes above threshold
    diffs     = np.diff(window)
    ssc_mask  = np.abs(np.diff(window[:-1])) >= threshold
    ssc       = int(np.sum((np.diff(np.sign(diffs)) != 0) & ssc_mask))

    var = float(np.var(window))

    return {'MAV': mav, 'RMS': rms, 'ZC': zc,
            'WL': wl,   'SSC': ssc, 'VAR': var}


def extract_windows(emg_multichannel, fs, window_ms=200, overlap=0.5):
    """
    Slide a window across all channels and concatenate per-channel
    features into one flat feature vector per window.

    Parameters
    ----------
    emg_multichannel : (n_samples, n_channels) ndarray
    fs               : sampling frequency
    window_ms        : window size in milliseconds
    overlap          : fractional overlap between adjacent windows

    Returns
    -------
    X            : (n_windows, n_features) ndarray
    feature_names: list[str]
    """
    n_samples, n_channels = emg_multichannel.shape
    win_samples = int(window_ms * fs / 1000)
    hop         = int(win_samples * (1 - overlap))

    rows = []
    for start in range(0, n_samples - win_samples, hop):
        row = {}
        for ch in range(n_channels):
            win   = emg_multichannel[start:start + win_samples, ch]
            feats = compute_features(win)
            row.update({f'ch{ch}_{k}': v for k, v in feats.items()})
        rows.append(row)

    df = pd.DataFrame(rows)
    return df.values, df.columns.tolist()


