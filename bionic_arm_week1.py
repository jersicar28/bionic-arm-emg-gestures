# --- 2. Bandpass Filter (20-450 Hz) ---
def bandpass_filter(data, lowcut=20, highcut=450, fs=fs, order=4):
    nyq = 0.5 * fs
    b, a = signal.butter(order, [lowcut/nyq, highcut/nyq], btype='band')
    return signal.filtfilt(b, a, data)

# --- 3. Notch Filter (60 Hz for US power line noise) ---
def notch_filter(data, freq=60, fs=fs, Q=30):
    b, a = signal.iirnotch(freq / (fs / 2), Q)
    return signal.filtfilt(b, a, data)

# --- 4. Full-Wave Rectification ---
def rectify(data):
    return np.abs(data)

# --- 5. Add a proper time axis to the envelope plo ---
def rms_envelope(data, window_ms=200, fs=fs):
    window_samples = int(window_ms * fs / 1000)
    rms = np.array([
        np.sqrt(np.mean(data[i:i+window_samples]**2))
        for i in range(0, len(data) - window_samples, window_samples // 2)
    ])
    return rms

