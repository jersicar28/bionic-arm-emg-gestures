import wfdb
import numpy as np
import scipy.signal as signal
import matplotlib.pyplot as plt

def full_pipeline(record_name):
    record = wfdb.rdrecord(record_name)
    emg = record.p_signal[:, 0]
    fs = record.fs
    # bandpass
    nyq = 0.5 * fs
    b, a = signal.butter(4, [20/nyq, 450/nyq], btype='band')
    emg = signal.filtfilt(b, a, emg)
    # notch
    b, a = signal.iirnotch(60 / (fs / 2), 30)
    emg = signal.filtfilt(b, a, emg)
    # rectify + envelope
    emg = np.abs(emg)
    window_samples = int(200 * fs / 1000)
    hop = window_samples // 2
    envelope = np.array([
        np.sqrt(np.mean(emg[i:i+window_samples]**2))
        for i in range(0, len(emg) - window_samples, hop)
    ])
    time_axis = np.arange(len(envelope)) * hop / fs
    return time_axis, envelope

# Plot gestures 1-4 for comparison
fig, axes = plt.subplots(4, 1, figsize=(12, 10))
gesture_names = ['Wrist Extension', 'Wrist Flexion', 'Gesture 3', 'Gesture 4']

for i, gesture_num in enumerate([1, 2, 3, 4]):
    t, env = full_pipeline(f'session1_participant1_gesture{gesture_num}_trial1')
    axes[i].plot(t, env)
    axes[i].set_title(f'Gesture {gesture_num}: {gesture_names[i]}')
    axes[i].set_ylabel('RMS Amplitude')
    axes[i].set_xlabel('Time (s)')

plt.tight_layout()
plt.show()

def extract_features(envelope_window):
    """Extract simple time-domain features from one RMS window"""
    return {
        'mean': np.mean(envelope_window),
        'std': np.std(envelope_window),
        'max': np.max(envelope_window),
        'min': np.min(envelope_window),
        'slope': np.polyfit(np.arange(len(envelope_window)), envelope_window, 1)[0]
    }

# Build a labeled feature dataset across gestures
import pandas as pd

rows = []
for gesture_num in range(1, 5):
    t, env = full_pipeline(f'session1_participant1_gesture{gesture_num}_trial1')
    features = extract_features(env)
    features['gesture'] = gesture_num
    rows.append(features)

