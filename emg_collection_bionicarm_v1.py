import asyncio
import csv
from datetime import datetime
from bleak import BleakClient, BleakScanner

# Must match your Arduino code
DEVICE_NAME = "MyoWareWS-1"
CHARACTERISTIC_UUID = "19b10001-e8f2-537e-4f6c-d104768a1214"

# Data storage
emg_data = []
start_time = None

def notification_handler(sender, data):
    """Called each time a BLE notification arrives."""
    global start_time

    if start_time is None:
        start_time = datetime.now()

    timestamp = (datetime.now() - start_time).total_seconds()
    value = data[0]  # Single byte (0-255) from current code

    emg_data.append({
        'timestamp': timestamp,
        'emg_value': value
    })

    # Print live feedback
    bar = '█' * (value // 5)
    print(f"{timestamp:8.3f}s | {value:3d} | {bar}")

async def main():
    print("Scanning for MyoWare device...")

    # Find device
    device = await BleakScanner.find_device_by_name(DEVICE_NAME, timeout=10.0)

    if device is None:
        print(f"Could not find device named '{DEVICE_NAME}'")
        print("Make sure the MyoWare is powered on and not connected to another device.")
        return

    print(f"Found {device.name} ({device.address})")
    print("Connecting...")

    async with BleakClient(device) as client:
        print("Connected! Starting data collection...")
        print("Press Ctrl+C to stop and save data.\n")
        print("Timestamp | Value | Signal")
        print("-" * 50)

        # Subscribe to notifications
        await client.start_notify(CHARACTERISTIC_UUID, notification_handler)

        try:
            # Run until interrupted
            while True:
                await asyncio.sleep(1)
        except KeyboardInterrupt:
            print("\n\nStopping data collection...")

        await client.stop_notify(CHARACTERISTIC_UUID)

    # Save data to CSV
    if emg_data:
        filename = f"emg_data_{datetime.now().strftime('%Y%m%d_%H%M%S')}.csv"
        with open(filename, 'w', newline='') as f:
            writer = csv.DictWriter(f, fieldnames=['timestamp', 'emg_value'])
            writer.writeheader()
            writer.writerows(emg_data)

        print(f"Saved {len(emg_data)} samples to {filename}")
        print(f"Duration: {emg_data[-1]['timestamp']:.2f} seconds")
        print(f"Effective sample rate: {len(emg_data) / emg_data[-1]['timestamp']:.1f} Hz")

if __name__ == "__main__":
    asyncio.run(main())